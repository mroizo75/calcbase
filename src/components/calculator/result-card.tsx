"use client";

import { useState } from "react";
import { Card, CardContent } from "@/components/ui/card";
import { Check, Copy, Download, FileText, Share2 } from "lucide-react";
import type { CalculatorResult } from "@/lib/calculators/types";

interface ResultCardProps {
  results: CalculatorResult[];
  formulaUsed?: string;
  shareUrl?: string;
  title?: string;
}

function slugify(text: string): string {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

export function ResultCard({ results, formulaUsed, shareUrl, title }: ResultCardProps) {
  const [copied, setCopied] = useState<"text" | "link" | null>(null);

  if (results.length === 0) return null;

  const heading = title ?? "Calculation Result";
  const summaryText = results.map((r) => `${r.label}: ${r.formatted}`).join("\n");
  const csvContent = [
    "Label,Value",
    ...results.map((r) => `"${r.label}","${r.formatted}"`),
  ].join("\n");

  async function handleShare() {
    if (!shareUrl) return;

    if (typeof navigator.share === "function") {
      try {
        await navigator.share({
          title: `${heading} – CalcBase`,
          text: summaryText,
          url: shareUrl,
        });
        return;
      } catch {
        /* User cancelled or not supported — fall through to clipboard */
      }
    }

    await navigator.clipboard.writeText(shareUrl);
    setCopied("link");
    setTimeout(() => setCopied(null), 2000);
  }

  async function handleCopyText() {
    await navigator.clipboard.writeText(summaryText);
    setCopied("text");
    setTimeout(() => setCopied(null), 2000);
  }

  function handleDownloadCsv() {
    const filename = `calcbase-${slugify(heading)}-${new Date().toISOString().slice(0, 10)}.csv`;
    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  }

  function handleExportPdf() {
    const rows = results
      .map((r) => `<tr${r.highlight ? ' class="highlight"' : ""}><td>${r.label}</td><td style="text-align:right">${r.formatted}</td></tr>`)
      .join("");
    const formulaRow = formulaUsed
      ? `<p class="formula">Formula: <code>${formulaUsed}</code></p>`
      : "";

    const html = `<!DOCTYPE html><html><head><title>${heading} – CalcBase</title>
<style>
  body{font-family:system-ui,sans-serif;max-width:600px;margin:40px auto;color:#1a1a1a}
  h1{font-size:20px;border-bottom:2px solid #1a1a1a;padding-bottom:8px}
  .meta{color:#666;font-size:13px;margin-bottom:20px}
  table{width:100%;border-collapse:collapse;margin:16px 0}
  th,td{text-align:left;padding:10px 12px;border-bottom:1px solid #e5e5e5}
  th{font-weight:600;color:#666;font-size:13px;text-transform:uppercase}
  .highlight td{font-weight:700;border-top:2px solid #1a1a1a;font-size:16px}
  .formula{margin-top:16px;font-size:12px;color:#666}
  .formula code{background:#f5f5f5;padding:2px 6px;border-radius:4px}
  .footer{margin-top:32px;font-size:11px;color:#999;border-top:1px solid #e5e5e5;padding-top:12px}
  @media print{body{margin:20px}}
</style></head><body>
<h1>${heading}</h1>
<p class="meta">Generated by CalcBase &middot; ${new Date().toLocaleDateString("en-GB")}</p>
<table><tr><th>Description</th><th style="text-align:right">Value</th></tr>${rows}</table>
${formulaRow}
<div class="footer">
<p>This is for informational purposes only and should not replace professional financial, tax, or legal advice.</p>
<p>calcbase.com</p>
</div></body></html>`;

    const w = window.open("", "_blank", "width=700,height=600");
    if (!w) return;
    w.document.write(html);
    w.document.close();
    w.focus();
    w.print();
  }

  return (
    <Card className="border-primary/20 bg-primary/[0.02]">
      <CardContent className="pt-6">
        <div className="mb-4 flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between">
          <h2 className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">
            Result
          </h2>
          <div className="flex flex-wrap gap-1">
            {shareUrl && (
              <button
                onClick={handleShare}
                className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
                aria-label="Share calculation"
                type="button"
              >
                {copied === "link" ? <Check className="h-4 w-4 sm:h-3.5 sm:w-3.5" /> : <Share2 className="h-4 w-4 sm:h-3.5 sm:w-3.5" />}
                {copied === "link" ? "Copied" : "Share"}
              </button>
            )}
            <button
              onClick={handleExportPdf}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label="Save as PDF"
              type="button"
            >
              <FileText className="h-4 w-4 sm:h-3.5 sm:w-3.5" />
              PDF
            </button>
            <button
              onClick={handleDownloadCsv}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label="Download CSV"
              type="button"
            >
              <Download className="h-4 w-4 sm:h-3.5 sm:w-3.5" />
              CSV
            </button>
            <button
              onClick={handleCopyText}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label="Copy result"
              type="button"
            >
              {copied === "text" ? <Check className="h-4 w-4 sm:h-3.5 sm:w-3.5" /> : <Copy className="h-4 w-4 sm:h-3.5 sm:w-3.5" />}
              {copied === "text" ? "Copied" : "Copy"}
            </button>
          </div>
        </div>

        <div className="space-y-3">
          {results.map((r) => (
            <div key={r.label} className="flex items-baseline justify-between gap-4">
              <span className="shrink-0 text-sm text-muted-foreground">{r.label}</span>
              <span
                className={`truncate text-right text-lg font-semibold tabular-nums ${r.highlight ? "text-primary" : ""}`}
              >
                {r.formatted}
              </span>
            </div>
          ))}
        </div>

        {formulaUsed && (
          <p className="mt-4 border-t pt-3 text-xs text-muted-foreground">
            Formula used:{" "}
            <code className="inline-block max-w-full break-all rounded bg-muted px-1 py-0.5">
              {formulaUsed}
            </code>
          </p>
        )}
      </CardContent>
    </Card>
  );
}
