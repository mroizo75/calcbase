"use client";

import { useState } from "react";
import { Card, CardContent } from "@/components/ui/card";
import { Check, Copy, Download, FileText, Share2 } from "lucide-react";
import type { CalculatorResult } from "@/lib/calculators/types";

/** All visible strings. Defaults are English; the Spanish pages pass their own set. */
export interface ResultCardLabels {
  calculationResult: string;
  result: string;
  csvLabel: string;
  csvValue: string;
  copyLink: string;
  linkCopied: string;
  downloadPdf: string;
  share: string;
  shareAria: string;
  copied: string;
  pdf: string;
  pdfAria: string;
  csv: string;
  csvAria: string;
  copy: string;
  copyAria: string;
  formulaUsed: string;
  pdfGeneratedBy: string;
  pdfDescription: string;
  pdfValue: string;
  pdfFormula: string;
  pdfDisclaimer: string;
  dateLocale: string;
  htmlLang: string;
}

export const DEFAULT_RESULT_CARD_LABELS: ResultCardLabels = {
  calculationResult: "Calculation Result",
  result: "Result",
  csvLabel: "Label",
  csvValue: "Value",
  copyLink: "Copy link",
  linkCopied: "Link copied",
  downloadPdf: "Download PDF",
  share: "Share",
  shareAria: "Share calculation",
  copied: "Copied",
  pdf: "PDF",
  pdfAria: "Save as PDF",
  csv: "CSV",
  csvAria: "Download CSV",
  copy: "Copy",
  copyAria: "Copy result",
  formulaUsed: "Formula used:",
  pdfGeneratedBy: "Generated by CalcBase",
  pdfDescription: "Description",
  pdfValue: "Value",
  pdfFormula: "Formula",
  pdfDisclaimer:
    "This is for informational purposes only and should not replace professional financial, tax, or legal advice.",
  dateLocale: "en-GB",
  htmlLang: "en",
};

interface ResultCardProps {
  results: CalculatorResult[];
  formulaUsed?: string;
  shareUrl?: string;
  title?: string;
  emphasizeExport?: boolean;
  /** Optional overrides for the visible text (used by the Spanish pages). */
  labels?: Partial<ResultCardLabels>;
}

function slugify(text: string): string {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

export function ResultCard({
  results,
  formulaUsed,
  shareUrl,
  title,
  emphasizeExport = false,
  labels,
}: ResultCardProps) {
  const L: ResultCardLabels = { ...DEFAULT_RESULT_CARD_LABELS, ...labels };
  const [copied, setCopied] = useState<"text" | "link" | null>(null);

  if (results.length === 0 && !emphasizeExport) return null;

  const heading = title ?? L.calculationResult;
  const summaryText = results.map((r) => `${r.label}: ${r.formatted}`).join("\n");
  const csvContent = [
    `${L.csvLabel},${L.csvValue}`,
    ...results.map((r) => `"${r.label}","${r.formatted}"`),
  ].join("\n");

  async function handleShare() {
    if (!shareUrl) return;

    if (typeof navigator.share === "function") {
      try {
        await navigator.share({
          title: `${heading} – CalcBase`,
          text: summaryText,
          url: shareUrl,
        });
        return;
      } catch {
        /* User cancelled or not supported — fall through to clipboard */
      }
    }

    await navigator.clipboard.writeText(shareUrl);
    setCopied("link");
    setTimeout(() => setCopied(null), 2000);
  }

  async function handleCopyText() {
    await navigator.clipboard.writeText(summaryText);
    setCopied("text");
    setTimeout(() => setCopied(null), 2000);
  }

  function handleDownloadCsv() {
    const filename = `calcbase-${slugify(heading)}-${new Date().toISOString().slice(0, 10)}.csv`;
    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  }

  function handleExportPdf() {
    const rows = results
      .map((r) => `<tr${r.highlight ? ' class="highlight"' : ""}><td>${r.label}</td><td style="text-align:right">${r.formatted}</td></tr>`)
      .join("");
    const formulaRow = formulaUsed
      ? `<p class="formula">${L.pdfFormula}: <code>${formulaUsed}</code></p>`
      : "";

    const html = `<!DOCTYPE html><html lang="${L.htmlLang}"><head><meta charset="utf-8"><title>${heading} – CalcBase</title>
<style>
  body{font-family:system-ui,sans-serif;max-width:600px;margin:40px auto;color:#1a1a1a}
  h1{font-size:20px;border-bottom:2px solid #1a1a1a;padding-bottom:8px}
  .meta{color:#666;font-size:13px;margin-bottom:20px}
  table{width:100%;border-collapse:collapse;margin:16px 0}
  th,td{text-align:left;padding:10px 12px;border-bottom:1px solid #e5e5e5}
  th{font-weight:600;color:#666;font-size:13px;text-transform:uppercase}
  .highlight td{font-weight:700;border-top:2px solid #1a1a1a;font-size:16px}
  .formula{margin-top:16px;font-size:12px;color:#666}
  .formula code{background:#f5f5f5;padding:2px 6px;border-radius:4px}
  .footer{margin-top:32px;font-size:11px;color:#999;border-top:1px solid #e5e5e5;padding-top:12px}
  @media print{body{margin:20px}}
</style></head><body>
<h1>${heading}</h1>
<p class="meta">${L.pdfGeneratedBy} &middot; ${new Date().toLocaleDateString(L.dateLocale)}</p>
<table><tr><th>${L.pdfDescription}</th><th style="text-align:right">${L.pdfValue}</th></tr>${rows}</table>
${formulaRow}
<div class="footer">
<p>${L.pdfDisclaimer}</p>
<p>calcbase.io</p>
</div></body></html>`;

    const w = window.open("", "_blank", "width=700,height=600");
    if (!w) return;
    w.document.write(html);
    w.document.close();
    w.focus();
    w.print();
  }

  return (
    <Card className="border-primary/20 bg-primary/[0.02]">
      <CardContent className="pt-6">
        {emphasizeExport && shareUrl ? (
          <div className="mb-4 flex flex-col gap-2 sm:flex-row">
            <button
              type="button"
              onClick={() => {
                void navigator.clipboard.writeText(shareUrl).then(() => {
                  setCopied("link");
                  setTimeout(() => setCopied(null), 2000);
                });
              }}
              className="inline-flex h-11 items-center justify-center rounded-lg bg-primary px-4 text-sm font-medium text-primary-foreground"
            >
              {copied === "link" ? L.linkCopied : L.copyLink}
            </button>
            <button
              type="button"
              onClick={handleExportPdf}
              className="inline-flex h-11 items-center justify-center rounded-lg border border-border bg-transparent px-4 text-sm font-medium text-foreground"
            >
              {L.downloadPdf}
            </button>
          </div>
        ) : null}
        <div className="mb-4 flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between">
          <h2 className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">
            {L.result}
          </h2>
          <div className="flex flex-wrap gap-1">
            {shareUrl && (
              <button
                onClick={handleShare}
                className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
                aria-label={L.shareAria}
                type="button"
              >
                {copied === "link" ? <Check className="h-4 w-4 sm:h-3.5 sm:w-3.5" /> : <Share2 className="h-4 w-4 sm:h-3.5 sm:w-3.5" />}
                {copied === "link" ? L.copied : L.share}
              </button>
            )}
            <button
              onClick={handleExportPdf}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label={L.pdfAria}
              type="button"
            >
              <FileText className="h-4 w-4 sm:h-3.5 sm:w-3.5" />
              {L.pdf}
            </button>
            <button
              onClick={handleDownloadCsv}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label={L.csvAria}
              type="button"
            >
              <Download className="h-4 w-4 sm:h-3.5 sm:w-3.5" />
              {L.csv}
            </button>
            <button
              onClick={handleCopyText}
              className="flex h-10 items-center gap-1.5 rounded-md px-3 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground sm:h-8 sm:px-2.5"
              aria-label={L.copyAria}
              type="button"
            >
              {copied === "text" ? <Check className="h-4 w-4 sm:h-3.5 sm:w-3.5" /> : <Copy className="h-4 w-4 sm:h-3.5 sm:w-3.5" />}
              {copied === "text" ? L.copied : L.copy}
            </button>
          </div>
        </div>

        <div className="space-y-3">
          {results.map((r) => (
            <div key={r.label} className="flex items-baseline justify-between gap-4">
              <span className="shrink-0 text-sm text-muted-foreground">{r.label}</span>
              <span
                className={`min-w-0 break-all text-right text-lg font-semibold tabular-nums ${r.highlight ? "text-primary" : ""}`}
              >
                {r.formatted}
              </span>
            </div>
          ))}
        </div>

        {formulaUsed && (
          <p className="mt-4 border-t pt-3 text-xs text-muted-foreground">
            {L.formulaUsed}{" "}
            <code className="inline-block max-w-full break-all rounded bg-muted px-1 py-0.5">
              {formulaUsed}
            </code>
          </p>
        )}
      </CardContent>
    </Card>
  );
}
